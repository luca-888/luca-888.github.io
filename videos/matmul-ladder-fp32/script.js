const SPK = (x) => (x.match(/[一-鿿]/g) || []).length * 0.21 + (x.match(/[A-Za-z0-9][A-Za-z0-9._\-]*/g) || []).length * 0.32 + (x.match(/[，；：、]/g) || []).length * 0.15;
const MEAS = typeof VODUR === 'undefined' || !VODUR ? {} : VODUR;
function scene(tag, head, src, beats, { min = 2.6, tail = 1.0, ...extra } = {}) {
  let t = 0.5; const out = [], stages = [], xs = [];
  for (const [st, act, vo, x = null] of beats) { out.push([+t.toFixed(1), act, vo]); stages.push(st); xs.push(x); t += vo ? Math.max(min, (MEAS[vo] !== undefined ? MEAS[vo] + 0.5 : SPK(vo) + 0.4)) : ((x && x.hold) || 2.2); }
  return { tag, head, src, stages, xs, dur: +(t - 0.6 + tail).toFixed(1), beats: out, ...extra };
}
